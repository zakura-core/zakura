"""Render selected aggregates without hiding seeds or failed reconstructions."""

from collections import defaultdict
import csv
import hashlib
import json
from pathlib import Path
import statistics
import sys


def mean(values):
    values = [x for x in values if x is not None]
    return statistics.mean(values) if values else None


def number(value, digits=2):
    return "—" if value is None else f"{value:.{digits}f}"


def main():
    root = Path(sys.argv[1])
    quick = json.loads((root / "environment.json").read_text())["quick"]
    lines = ["# Recorded results", "", "Generated by `summarize.py`. See the [report](../../README.md) for assumptions.", "",
             "## Codec", "", "Medians of three retained repetitions; the first repetition warms each process.",
             "These tails replay measured tasks on one serial worker at 1 ms part intervals.", "",
             "| Codec | Body MiB | Trace | Assemblies | Schedule | Encode ms | Recheck ms | Tail ms |",
             "| --- | ---: | --- | ---: | --- | ---: | ---: | ---: |"]
    groups = defaultdict(list)
    for r in csv.DictReader((root / "codec.csv").open()):
        if r["warmup"] == "0" and r["gap_ms"] == "1" and r["trace"] in ("systematic", "parity_first"):
            if int(r["n"]) == int(r["k"]) * 1.25:
                groups[r["codec"], int(r["k"]), r["trace"], r["assemblies"], r["schedule"]].append(r)
    for key, rows in sorted(groups.items()):
        codec, k, trace, assemblies, schedule = key
        values = [statistics.median(float(r[f]) for r in rows)
                  for f in ("encode_ms", "reencode_root_ms", "tail_ms")]
        lines.append(f"| {codec} | {k / 16:g} | {trace} | {assemblies} | {schedule} | " +
                     " | ".join(number(x) for x in values) + " |")

    lines += ["", "## Routing", "", f"Each row averages {2 if quick else 12} seeds with 80 blocks per seed.",
              "p95/p99 summarize completed reconstructions only. The bracketed p95 range spans seeds.",
              "Fallback marks failure to reconstruct by 1,200 ms; it is not a successful download.",
              "Wire/body divides receiver-link bytes by all offered body bytes, including failed blocks.", "",
              "| Scenario | Policy | p95 ms [min–max] | p99 ms | Miss % | Fallback % | Wire/body | Moves |",
              "| --- | --- | ---: | ---: | ---: | ---: | ---: | ---: |"]
    groups.clear()
    for line in (root / "routing.jsonl").read_text().splitlines():
        r = json.loads(line)
        groups[r["scenario"], r["policy"]].append(r)
    for (scenario, policy), rows in sorted(groups.items()):
        p95 = [r["p95_ms"] for r in rows if r["p95_ms"] is not None]
        interval = f"{mean(p95):.1f} [{min(p95):.1f}–{max(p95):.1f}]" if p95 else "—"
        values = [mean([r["p99_ms"] for r in rows]), 100 * mean([r["deadline_miss"] for r in rows]),
                  100 * mean([r["fallback"] for r in rows]), mean([r["wire_to_body"] for r in rows]),
                  mean([r["moves"] for r in rows])]
        lines.append(f"| {scenario} | {policy} | {interval} | " + " | ".join(number(x) for x in values) + " |")

    lines += ["", "## Challenge lifetime", "",
              "Means across the width, fraction, cadence, and seed sweep; not an isolated causal effect.", "",
              "| Proposer pattern | Age cap s | Moves | Expired trials | Decisive votes |",
              "| --- | ---: | ---: | ---: | ---: |"]
    groups.clear()
    for line in (root / "sweeps.jsonl").read_text().splitlines():
        r = json.loads(line)
        if r["scenario"] == "challenge_sweep":
            groups[r["config"]["proposer_mode"], r["config"]["trial_age_ms"]].append(r)
    for (mode, age), rows in sorted(groups.items()):
        lines.append(f"| {mode} | {age / 1000:g} | " + " | ".join(
            number(mean([r[f] for r in rows])) for f in ("moves", "expired", "votes")) + " |")

    lines += ["", "## Observation errors", "",
              f"{40 if quick else 400} seeds per row. A has lower expected same-part delay in every case.",
              "Different-part means use more samples than paired votes. This is not an equal-cost comparison.", "",
              "| Distribution | Blocks | Different-part mean wrong % | Raw-count wrong % | Paired wrong % | Paired inconclusive % |",
              "| --- | ---: | ---: | ---: | ---: | ---: |"]
    for r in json.loads((root / "observations.json").read_text()):
        lines.append(f"| {r['mode']} | {r['blocks']} | " + " | ".join(
            number(100 * r[f]) for f in ("passive_wrong", "count_wrong", "paired_wrong", "paired_inconclusive")) + " |")

    lines += ["", "## Reachability", "",
              f"Static connected graphs, 64 nodes, minimum degree 8, {4 if quick else 40} seeds.",
              "The source holds every part. Regeneration starts after k distinct parts.", "",
              "| Parity/data | Suppliers per part | Regenerate | Repair | Mean completed nodes | Runs reaching every node |",
              "| ---: | ---: | --- | --- | ---: | ---: |"]
    groups.clear()
    for r in json.loads((root / "graph.json").read_text()):
        if r["nodes"] == 64 and r["minimum_degree"] == 8:
            groups[r["parity"], r["copies"], r["regenerate"], r["repair"]].append(r)
    for (ratio, copies, regenerate, repair), rows in sorted(groups.items()):
        lines.append(f"| {ratio:g} | {copies} | {regenerate} | {repair} | {mean([r['completed'] for r in rows]):.2f} | "
                     f"{sum(r['completed'] == 64 for r in rows)}/{len(rows)} |")
    (root / "SUMMARY.md").write_text("\n".join(lines) + "\n")
    manifest = {p.name: hashlib.sha256(p.read_bytes()).hexdigest() for p in sorted(root.iterdir())
                if p.is_file() and p.name != "SHA256SUMS.json"}
    (root / "SHA256SUMS.json").write_text(json.dumps(manifest, indent=2, sort_keys=True) + "\n")


if __name__ == "__main__":
    main()
